/**
 * Стриминговый вызов DeepSeek API для консультанта
 * Используется в /api/consultant route
 */
export interface Message {
  role: 'user' | 'assistant'
  content: string
}

export async function streamConsultant(
  messages: Message[],
  calculationContext?: string
): Promise<ReadableStream> {
  const systemPrompt = calculationContext
    ? `${ELECTRICAL_SYSTEM_PROMPT}\n\n## Контекст текущего расчёта пользователя:\n${calculationContext}`
    : ELECTRICAL_SYSTEM_PROMPT

  const response = await fetch('https://api.deepseek.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${process.env.DEEPSEEK_API_KEY}`,
    },
    body: JSON.stringify({
      model: 'deepseek-chat',
      max_tokens: 1024,
      messages: [
        { role: 'system', content: systemPrompt },
        ...messages,
      ],
      stream: true,
    }),
  })

  if (!response.ok) {
    throw new Error(`DeepSeek API error: ${response.status} ${response.statusText}`)
  }

  return response.body!
}

